from src.llm.service import LLMService
from src.llm.prompts import PromptBuilder
from src.rag.service import RAGService



class RAGLLMService:

    def __init__(self, rag_service: RAGService, llm_service: LLMService):

        self.rag_service = rag_service
        self.llm_service = llm_service
    
    def answer(self, question: str, k: int = 5) -> str:
        """
        Answer a question using the RAG approach.

        Args:
            question (str): The input question to answer.
            k (int): The number of top results to retrieve for context. Default is 5.

        Returns:
            str: The answer generated by the LLM based on the retrieved context.
        """
        context = self.rag_service.retrieve_context(question, k=k)

        # if not context:
        #     return "No relevant information found in the knowledge base."

        prompt = PromptBuilder.build_rag_prompt(
            question=question,
            context=context,
        )

        answer = self.llm_service.generate_text(prompt)

        return answer